/// Check whether a feature is present in an active features set.
///
/// The set uses raw 32-byte keys to avoid coupling with any specific
/// pubkey or feature-set type.
#[inline]
pub fn is_feature_active(
    active_features: &std::collections::HashSet<[u8; 32]>,
    feature_id: &Pubkey,
) -> bool {
    active_features.contains(feature_id.as_bytes())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn feature_ids_are_32_bytes() {
        let features = [
            ENABLE_LOADER_V4,
            ENABLE_SECP256R1_PRECOMPILE,
            MOVE_PRECOMPILE_VERIFICATION_TO_SVM,
            ENABLE_BPF_LOADER_SET_AUTHORITY_CHECKED,
            ENABLE_EXTEND_PROGRAM_CHECKED,
            ACCOUNT_DATA_DIRECT_MAPPING,
            STRICTER_ABI_AND_RUNTIME_CONSTRAINTS,
            DEPLETE_CU_METER_ON_VM_FAILURE,
            BLAKE3_SYSCALL_ENABLED,
            CURVE25519_SYSCALL_ENABLED,
            ENABLE_ALT_BN128_SYSCALL,
            ENABLE_ALT_BN128_COMPRESSION_SYSCALL,
            ENABLE_POSEIDON_SYSCALL,
            REMAINING_COMPUTE_UNITS_SYSCALL_ENABLED,
            ABORT_ON_INVALID_CURVE,
            ENABLE_GET_EPOCH_STAKE_SYSCALL,
            INCREASE_TX_ACCOUNT_LOCK_LIMIT,
        ];
        for f in &features {
            assert_eq!(f.as_bytes().len(), 32);
        }
    }

    #[test]
    fn all_feature_ids_are_unique() {
        let features = [
            ENABLE_LOADER_V4,
            ENABLE_SECP256R1_PRECOMPILE,
            MOVE_PRECOMPILE_VERIFICATION_TO_SVM,
            ENABLE_BPF_LOADER_SET_AUTHORITY_CHECKED,
            ENABLE_EXTEND_PROGRAM_CHECKED,
            ACCOUNT_DATA_DIRECT_MAPPING,
            STRICTER_ABI_AND_RUNTIME_CONSTRAINTS,
            DEPLETE_CU_METER_ON_VM_FAILURE,
            BLAKE3_SYSCALL_ENABLED,
            CURVE25519_SYSCALL_ENABLED,
            ENABLE_ALT_BN128_SYSCALL,
            ENABLE_ALT_BN128_COMPRESSION_SYSCALL,
            ENABLE_POSEIDON_SYSCALL,
            REMAINING_COMPUTE_UNITS_SYSCALL_ENABLED,
            ABORT_ON_INVALID_CURVE,
            ENABLE_GET_EPOCH_STAKE_SYSCALL,
            INCREASE_TX_ACCOUNT_LOCK_LIMIT,
        ];
        let set: HashSet<[u8; 32]> = features.iter().map(|f| *f.as_bytes()).collect();
        assert_eq!(set.len(), features.len(), "duplicate feature IDs detected");
    }

    #[test]
    fn is_feature_active_finds_present() {
        let mut active = HashSet::new();
        active.insert(*ENABLE_LOADER_V4.as_bytes());

        assert!(is_feature_active(&active, &ENABLE_LOADER_V4));
        assert!(!is_feature_active(&active, &ENABLE_SECP256R1_PRECOMPILE));
    }

    #[test]
    fn is_feature_active_empty_set_returns_false() {
        let active = HashSet::new();
        assert!(!is_feature_active(&active, &ENABLE_LOADER_V4));
    }
}
