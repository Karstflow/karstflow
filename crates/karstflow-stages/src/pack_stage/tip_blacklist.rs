/// Tip payment program blacklist for the pack scheduler.
///
/// Prevents transactions from accessing tip infrastructure accounts
/// in unauthorized ways. Bundle transactions may not invoke the tip
/// program directly (prevents tip redirection attacks). Non-bundle
/// transactions may not access any tip-related accounts (prevents
/// contention with the tip mechanism).
///
/// The blacklist covers both mainnet and testnet tip programs, config
/// accounts, and tip receiver accounts (20 accounts total).
use karstflow_types::Pubkey;

/// Result of checking an account against the tip blacklist.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TipBlacklistResult {
    /// Account is not in the blacklist — allowed everywhere.
    Allowed,
    /// Account is forbidden for non-bundle transactions only (tip/config accounts).
    ForbiddenNonBundle,
    /// Account is forbidden for both bundle and non-bundle transactions
    /// (the tip program itself).
    ForbiddenAll,
}

