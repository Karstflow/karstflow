/// Total number of blacklisted accounts (mainnet + testnet).
/// 2 programs + 2 configs + 8 mainnet tips + 8 testnet tips = 20.
pub const TIP_BLACKLIST_COUNT: usize = 20;

/// Check if an account is in the tip program blacklist.
///
/// Returns the blacklist status:
/// - `Allowed`: account is not blacklisted
/// - `ForbiddenNonBundle`: forbidden for non-bundle transactions (tip/config accounts)
/// - `ForbiddenAll`: forbidden for all transaction types (tip programs)
pub fn check_tip_blacklist(account: &Pubkey) -> TipBlacklistResult {
    // Check tip programs (forbidden for all)
    if *account == MAINNET_TIP_PROGRAM || *account == TESTNET_TIP_PROGRAM {
        return TipBlacklistResult::ForbiddenAll;
    }

    // Check config accounts (forbidden for non-bundles)
    if *account == MAINNET_TIP_CONFIG || *account == TESTNET_TIP_CONFIG {
        return TipBlacklistResult::ForbiddenNonBundle;
    }

    // Check tip receiver accounts (forbidden for non-bundles)
    for tip_account in &MAINNET_TIP_ACCOUNTS {
        if account == tip_account {
            return TipBlacklistResult::ForbiddenNonBundle;
        }
    }
    for tip_account in &TESTNET_TIP_ACCOUNTS {
        if account == tip_account {
            return TipBlacklistResult::ForbiddenNonBundle;
        }
    }

    TipBlacklistResult::Allowed
}

/// Check if an account is a tip receiver account (not the program or config).
pub fn is_tip_receiver(account: &Pubkey) -> bool {
    for tip_account in &MAINNET_TIP_ACCOUNTS {
        if account == tip_account {
            return true;
        }
    }
    for tip_account in &TESTNET_TIP_ACCOUNTS {
        if account == tip_account {
            return true;
        }
    }
    false
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mainnet_tip_program_forbidden_all() {
        assert_eq!(
            check_tip_blacklist(&MAINNET_TIP_PROGRAM),
            TipBlacklistResult::ForbiddenAll
        );
    }

    #[test]
    fn testnet_tip_program_forbidden_all() {
        assert_eq!(
            check_tip_blacklist(&TESTNET_TIP_PROGRAM),
            TipBlacklistResult::ForbiddenAll
        );
    }

    #[test]
    fn mainnet_config_forbidden_non_bundle() {
        assert_eq!(
            check_tip_blacklist(&MAINNET_TIP_CONFIG),
            TipBlacklistResult::ForbiddenNonBundle
        );
    }

    #[test]
    fn testnet_config_forbidden_non_bundle() {
        assert_eq!(
            check_tip_blacklist(&TESTNET_TIP_CONFIG),
            TipBlacklistResult::ForbiddenNonBundle
        );
    }

    #[test]
    fn mainnet_tip_accounts_forbidden_non_bundle() {
        for account in &MAINNET_TIP_ACCOUNTS {
            assert_eq!(
                check_tip_blacklist(account),
                TipBlacklistResult::ForbiddenNonBundle,
            );
        }
    }

    #[test]
    fn testnet_tip_accounts_forbidden_non_bundle() {
        for account in &TESTNET_TIP_ACCOUNTS {
            assert_eq!(
                check_tip_blacklist(account),
                TipBlacklistResult::ForbiddenNonBundle,
            );
        }
    }

    #[test]
    fn random_account_is_allowed() {
        let random = Pubkey::new([0xFF; 32]);
        assert_eq!(check_tip_blacklist(&random), TipBlacklistResult::Allowed);
    }

    #[test]
    fn tip_receiver_detection() {
        assert!(is_tip_receiver(&MAINNET_TIP_ACCOUNTS[0]));
        assert!(is_tip_receiver(&MAINNET_TIP_ACCOUNTS[7]));
        assert!(is_tip_receiver(&TESTNET_TIP_ACCOUNTS[3]));
        assert!(is_tip_receiver(&TESTNET_TIP_ACCOUNTS[7]));
        assert!(!is_tip_receiver(&MAINNET_TIP_PROGRAM));
        assert!(!is_tip_receiver(&MAINNET_TIP_CONFIG));
        assert!(!is_tip_receiver(&Pubkey::new([0xFF; 32])));
    }

    #[test]
    fn blacklist_count_matches() {
        let mut count = 0;
        count += 2; // programs
        count += 2; // configs
        count += MAINNET_TIP_ACCOUNTS.len() + TESTNET_TIP_ACCOUNTS.len();
        assert_eq!(count, TIP_BLACKLIST_COUNT);
    }

    #[test]
    fn all_blacklisted_accounts_unique() {
        let mut seen = std::collections::HashSet::new();
        assert!(seen.insert(*MAINNET_TIP_PROGRAM.as_bytes()));
        assert!(seen.insert(*TESTNET_TIP_PROGRAM.as_bytes()));
        assert!(seen.insert(*MAINNET_TIP_CONFIG.as_bytes()));
        assert!(seen.insert(*TESTNET_TIP_CONFIG.as_bytes()));
        for a in &MAINNET_TIP_ACCOUNTS {
            assert!(seen.insert(*a.as_bytes()), "Duplicate mainnet tip account");
        }
        for a in &TESTNET_TIP_ACCOUNTS {
            assert!(seen.insert(*a.as_bytes()), "Duplicate testnet tip account");
        }
        assert_eq!(seen.len(), TIP_BLACKLIST_COUNT);
    }
}
